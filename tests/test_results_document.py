"""Documents with generated tables must match the committed JSON results.

Tables in RESULTS.md, README.md and the E10 summary are generated by ``asr-lab render-results``,
never typed, so numbers cannot drift from the results in experiments/.
"""

from pathlib import Path

import pytest

from asr_lab.reporting import render_results

SPECS = sorted(Path("experiments").glob("*/tables.toml"))
# Document and whether it may show only some of the tables.
DOCUMENTS = [
    (Path("RESULTS.md"), False),
    (Path("README.md"), True),
    (Path("reports/e10_summary.md"), True),
]


@pytest.mark.skipif(not SPECS, reason="no experiment results yet")
@pytest.mark.parametrize(("document", "partial"), DOCUMENTS)
def test_documents_are_up_to_date(document: Path, partial: bool) -> None:
    outdated = render_results(SPECS, document, check=True, allow_missing=partial)
    flag = " --allow-missing-markers" if partial else ""
    assert not outdated, (
        f"{document} does not match the results in experiments/: run `uv run asr-lab "
        f"render-results --document {document}{flag} "
        + " ".join(f"--spec {spec}" for spec in SPECS)
        + "`"
    )
